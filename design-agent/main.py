"""
design-agent – CogniOps Design-Time Agent.

Batch/scheduled service that:
  1. Builds analysis context from BQ metrics + GCS config
  2. Runs ADK LlmAgent for structural analysis
  3. Validates proposal (deterministic)
  4. Stores proposal in GCS + creates GitHub Issue

Endpoints:
  POST /run          – Trigger analysis (Cloud Scheduler or manual)
  GET  /health       – Liveness probe
  GET  /agent/info   – ADK agent metadata

Trigger: Cloud Scheduler HTTP POST (weekly) or manual workflow_dispatch.
"""

